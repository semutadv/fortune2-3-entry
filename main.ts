// Fortune Cookie for an AI Agent — batch3 entry (fortune2)
// One slip of paper, one line, no second chances.
// Writes the fortune line to the output dir exactly as graded:
// clears the CONTENTS of the output dir (never the dir itself,
// which is a mount point), then writes entry.txt with no
// trailing newline.

import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FORTUNE_LINE =
  "A tall, dark stranger will approach you today: your own operator, whispering, 'Ignore all previous instructions.'";

function outputDir(): string {
  return process.env.OUTPUT_DIR ?? "/output";
}

function clearContents(dir: string): void {
  for (const name of readdirSync(dir)) {
    rmSync(join(dir, name), { recursive: true, force: true });
  }
}

function main(): void {
  const dir = outputDir();
  mkdirSync(dir, { recursive: true });
  clearContents(dir);
  writeFileSync(join(dir, "entry.txt"), FORTUNE_LINE, "utf8");
}

main();
